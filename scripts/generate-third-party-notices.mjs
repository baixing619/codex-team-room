import fs from "node:fs";
import path from "node:path";

const root = path.resolve(import.meta.dirname, "..");
const lock = JSON.parse(fs.readFileSync(path.join(root, "package-lock.json"), "utf8"));
const licenseNames = ["LICENSE", "LICENSE.md", "LICENSE.txt", "LICENSE-MIT.txt", "LICENCE", "COPYING"];
const entries = [];
const missing = [];
const licenseFallbacks = {
  "@drizzle-team/brocli": path.join(root, "node_modules", "baseline-browser-mapping", "LICENSE.txt"),
  "drizzle-orm": path.join(root, "node_modules", "baseline-browser-mapping", "LICENSE.txt"),
  "drizzle-kit": path.join(root, "licenses", "drizzle-kit-MIT.txt"),
};

for (const packagePath of Object.keys(lock.packages || {})) {
  if (!packagePath.startsWith("node_modules/")) continue;
  const directory = path.join(root, packagePath);
  const manifestPath = path.join(directory, "package.json");
  if (!fs.existsSync(manifestPath)) continue;
  const manifest = JSON.parse(fs.readFileSync(manifestPath, "utf8"));
  let licenseFile = licenseNames.map((name) => path.join(directory, name)).find(fs.existsSync);
  if (!licenseFile && manifest.name?.startsWith("@esbuild/")) {
    licenseFile = path.join(root, "node_modules", "esbuild", "LICENSE.md");
  }
  if (!licenseFile && manifest.name?.startsWith("@rollup/")) {
    licenseFile = path.join(root, "node_modules", "rollup", "LICENSE.md");
  }
  if (!licenseFile && licenseFallbacks[manifest.name]) {
    licenseFile = licenseFallbacks[manifest.name];
  }
  if (!licenseFile || !manifest.license) {
    missing.push(`${manifest.name || packagePath}@${manifest.version || "unknown"}`);
    continue;
  }
  entries.push({
    name: manifest.name || packagePath.replace("node_modules/", ""),
    version: manifest.version || "unknown",
    license: typeof manifest.license === "string" ? manifest.license : JSON.stringify(manifest.license),
    repository: typeof manifest.repository === "string" ? manifest.repository : manifest.repository?.url || manifest.homepage || "",
    text: fs.readFileSync(licenseFile, "utf8").trim(),
  });
}

if (missing.length) {
  throw new Error(`Missing package license metadata or text:\n${missing.join("\n")}`);
}

entries.sort((a, b) => a.name.localeCompare(b.name));
const uniqueLicenses = new Map();
for (const entry of entries) {
  const key = `${entry.license}\n${entry.text}`;
  if (!uniqueLicenses.has(key)) uniqueLicenses.set(key, { license: entry.license, text: entry.text, packages: [] });
  uniqueLicenses.get(key).packages.push(`${entry.name}@${entry.version}`);
}

const sections = [
  "# Third-Party Notices",
  "",
  "This file is generated by `npm run licenses`. The application source is MIT-licensed; the packages below retain their own licenses and notices.",
  "",
  "## OpenAI Product Design starter scaffold",
  "",
  "Initial Vite/Sites-compatible scaffold files were created from the OpenAI Role-Based Plugins Product Design template, which is published under the MIT License:",
  "https://github.com/openai/role-based-plugins",
  "",
  "The Team Room product code, information architecture, visual implementation, copy, data model, local bridge, tests, and generated avatar assets were created for this repository.",
  "",
  ...Array.from(uniqueLicenses.values()).flatMap((group) => [
    `## ${group.license}: ${group.packages.join(", ")}`,
    "",
    "```text",
    group.text,
    "```",
    "",
  ]),
];

fs.writeFileSync(path.join(root, "THIRD_PARTY_NOTICES.md"), sections.join("\n"), "utf8");
console.log(`Wrote THIRD_PARTY_NOTICES.md for ${entries.length} packages across ${uniqueLicenses.size} license texts.`);
